//! **신뢰를 깨는 말을 빌드가 막는다.**
//!
//! ## 🔴 왜 이 파일이 있나
//!
//! 대표님(2026-08-29):
//!
//! > 우리 시스템의 핵심으로 원하는 것은 **신뢰**거든. 민주주의에서 악행을
//! > 막으려면 신뢰를 기반으로 만들어야 해. **신뢰라는 시스템을 저해하는
//! > 행위는 용납하지 않아.**
//!
//! 그리고 그날 하루 동안 찾은 것들이 전부 같은 병이었다 —
//! **기능이 없어서가 아니라 있는 척해서** 신뢰가 깨졌다:
//!
//! ```text
//! 「몇 분 기다리세요」              실제로는 한 달
//! 「체인은 누가 보냈는지 모릅니다」   실제로는 안다
//! 「대비책이 있습니다」              한 번도 작동한 적 없음
//! 「결제됨」                        실제로는 상태를 모를 때의 기본값
//! 「매출 0」                        실제로는 장부에 안 써진 것
//! ```
//!
//! 사장은 그 말을 믿고 장사한다. 손님은 그 화면을 믿고 돈을 보낸다.
//! **한 번 어긋나면 기능을 백 개 붙여도 안 돌아온다.**
//!
//! ## 이 저장소가 신뢰를 지키는 방식
//!
//! 말로 다짐하지 않는다. **빌드가 막는다.**
//!
//! ```text
//! noncustody.rs   우리가 남의 돈을 드는 코드가 들어오면 빌드 실패
//! wording.rs      투자로 읽히는 낱말이 들어오면 빌드 실패
//! trust.rs        ← 여기. 지키지 못할 말이 들어오면 빌드 실패
//! ```
//!
//! ## ⚠️ 이 검사의 한계를 정직하게 적는다
//!
//! 낱말을 보는 검사다. **뜻을 보지 못한다.** 「곧 됩니다」를 막아도 「금방
//! 끝나요」로 쓰면 지나간다. 그래서 이건 **기억을 돕는 장치**이지 보증이
//! 아니다. 진짜 보증은 사람이 재보고 적는 것이다 — 그 사실을 여기 적어
//! 두는 것도 신뢰다.

/// 검사할 때는 **주석을 뺀다.**
///
/// ⚠️ 안 그러면 이 파일의 설명글에 적힌 「몇 분」 같은 낱말을 검사가
///    스스로 잡는다. 이 저장소에서 여러 번 밟은 함정이다.
#[cfg(test)]
fn 사람이_보는_글만(src: &str) -> String {
    src.split("#[cfg(test)]")
        .next()
        .unwrap_or(src)
        .lines()
        .filter(|l| {
            let t = l.trim_start();
            !t.starts_with("//") && !t.starts_with("///") && !t.starts_with("//!")
        })
        .collect::<Vec<_>>()
        .join("\n")
}

#[cfg(test)]
mod 신뢰 {
    use super::사람이_보는_글만;

    /// 🔴 **재보지 않은 시간을 말하지 않는다.**
    ///
    /// 2026-08-29 실측: `health.rs` 가 「몇 분 기다리세요」라고 했는데
    /// 같은 저장소의 다른 주석에는 **한 달**이라는 실측이 적혀 있었다.
    /// 첫 실행 사장이 정확히 그 상태였다.
    ///
    /// 며칠 걸릴 일을 「몇 분」이라 하면 사장은 몇 분 뒤 고장 났다고
    /// 판단하고 **프로그램을 지운다.** 그리고 다시 안 깐다.
    ///
    /// 모르면 **모른다고 하는 편이 낫다.** 「얼마나 걸리는지는 …에서 보실
    /// 수 있습니다」가 「몇 분」보다 정직하고, 정직한 쪽이 덜 무섭다.
    #[test]
    fn 재보지_않은_시간을_말하지_않는다() {
        // 사장이 기다리는 화면들. 여기서 시간을 지어내면 바로 신뢰가 깨진다.
        for (파일, 글) in [
            ("health.rs", 사람이_보는_글만(include_str!("health.rs"))),
            ("services.rs", 사람이_보는_글만(include_str!("services.rs"))),
        ] {
            for 지어낸말 in ["몇 분", "곧 됩니다", "금방 끝", "잠시만 기다"] {
                assert!(
                    !글.contains(지어낸말),
                    "{파일} 에 「{지어낸말}」 이 있습니다. **재보지 않은 시간입니다.** \
                     며칠 걸릴 일을 몇 분이라 하면 사장은 고장 났다고 여기고 프로그램을 \
                     지웁니다. 모르면 모른다고 하고, 어디서 남은 시간을 볼 수 있는지 \
                     알려 주세요."
                );
            }
        }
    }

    /// 🔴 **없는 것과 못 본 것을 갈라 적는다.**
    ///
    /// 공개 조회처는 자산을 못 본다. 그걸 「자산 0」으로 돌려주면 회원권을
    /// 산 사람이 **안 샀다고 여긴다.** 지갑이 할 수 있는 가장 나쁜 거짓말이다.
    ///
    /// 그래서 `publicbook.rs` 는 `assets_unknown` 을 켜서 돌려준다.
    /// 이 검사는 그 습관이 사라지지 않게 지킨다.
    #[test]
    fn 못_본_것을_없다고_하지_않는다() {
        let 글 = 사람이_보는_글만(include_str!("publicbook.rs"));
        assert!(
            글.contains("assets_unknown"),
            "공개 조회처가 자산을 못 보는데 그 사실을 안 알리고 있습니다. \
             「0」과 「모름」은 다릅니다 — 회원권을 산 사람이 안 샀다고 여깁니다."
        );
    }

    /// 🔴 **못 지킬 약속을 적지 않는다.**
    ///
    /// 경쟁 서비스는 「서비스 종료 시 30일 전 서명된 통지」를 약속한다.
    /// 우리는 **그걸 실행할 주체도 연락 수단도 없다.** 적으면 거짓말이다.
    ///
    /// 적어도 되는 것은 **이미 코드가 강제하는 것**뿐이다:
    ///   · 열쇠를 우리가 안 쥔다 (`noncustody.rs` 가 빌드로 막는다)
    ///   · 12단어는 표준 경로라 다른 지갑에서 그대로 열린다
    ///   · 앱이 사라져도 노드와 잔고는 사장 컴퓨터에 남는다
    #[test]
    fn 못_지킬_약속을_적지_않는다() {
        for (파일, 글) in [
            ("moving.rs", 사람이_보는_글만(include_str!("moving.rs"))),
            ("backup.rs", 사람이_보는_글만(include_str!("backup.rs"))),
        ] {
            for 못지킬말 in ["평생", "영원히 보장", "절대 안 됩니다", "100% 안전"] {
                assert!(
                    !글.contains(못지킬말),
                    "{파일} 에 「{못지킬말}」 이 있습니다. **우리가 지킬 수 있는 약속만** \
                     적습니다. 지키지 못할 약속은 지금 안심시키고 나중에 신뢰를 통째로 \
                     가져갑니다."
                );
            }
        }
    }

    /// 🔴 **안 되는 것을 되는 척하지 않는다.**
    ///
    /// 대표님이 「내보내기(강퇴)」를 물으셨을 때 만들지 않은 이유다.
    /// 릴레이는 세계에 흩어져 있어 **방장에게도 남의 글을 막을 권한이 없다.**
    /// 단추를 만들면 눌러도 그 사람은 계속 쓰고, 사장은 「막았다」고 믿는다.
    /// **그게 안 막는 것보다 나쁘다.**
    ///
    /// 그래서 「안 보기」만 만들고 화면에 그렇게 적었다.
    #[test]
    fn 안_되는_것을_되는_척하지_않는다() {
        let ts = include_str!("../../src/main.ts");
        let 화면: String = ts
            .lines()
            .filter(|l| {
                let t = l.trim_start();
                !t.starts_with("//") && !t.starts_with("*")
            })
            .collect::<Vec<_>>()
            .join("\n");
        // 「안 보기」를 만들었으면 **그 한계도 같이** 적혀 있어야 한다.
        if 화면.contains("안 보기") {
            assert!(
                화면.contains("그 사람은 계속"),
                "「안 보기」를 만들었으면 **내 화면에서만 숨긴다는 사실**을 화면에 \
                 적어야 합니다. 안 적으면 사장은 상대를 막았다고 믿습니다."
            );
        }
        // 「내보내기·강퇴」 단추는 애초에 있으면 안 된다.
        for 못하는일 in ["강퇴", "내보내기 버튼", "쫓아내기"] {
            assert!(
                !화면.contains(못하는일),
                "화면에 「{못하는일}」 이 있습니다. 릴레이는 세계에 흩어져 있어 \
                 **우리는 남을 못 막습니다.** 되는 척하면 사장이 막았다고 믿고, \
                 그게 안 막는 것보다 나쁩니다."
            );
        }
    }

    /// 🔴 **`async` 안에서 `block_on` 을 부르지 않는다.**
    ///
    /// 런타임 안에서 런타임을 시작하려다 **그 자리에서 터진다**
    /// (`Cannot start a runtime from within a runtime`). 사장은 단추를
    /// 눌렀는데 아무 말도 없이 앱이 죽는 것을 본다.
    ///
    /// ⚠️ **검사로는 안 잡힌다** — 시험은 런타임 밖에서 도니까 통과한다.
    ///    「통과가 작동의 증거가 아닌」 자리라 여기서 글자로 막는다.
    ///    (2026-08-29 `shopmove.rs` 에서 실제로 이 모양을 찾아 고쳤다.)
    #[test]
    fn 런타임_안에서_런타임을_시작하지_않는다() {
        for (파일, src) in [
            ("shopmove.rs", include_str!("shopmove.rs")),
            ("identity.rs", include_str!("identity.rs")),
            ("shopkey.rs", include_str!("shopkey.rs")),
            ("talk.rs", include_str!("talk.rs")),
        ] {
            let 코드 = 사람이_보는_글만(src);
            // ⚠️ **파일 단위로 보면 안 된다.** sync 함수 안의 `block_on` 은
            //    정상이다 — sync 인 곳에서 async 를 부르려면 그 길뿐이다.
            //    (이 검사를 처음 만들었을 때 `identity.rs` 를 잘못 잡았다.
            //     거기는 sync·async 를 **일부러 나눠 두고 이유까지 적어** 놨다.
            //     안전장치가 좋은 것을 막으면 사람이 안전장치를 끈다.)
            //
            //    **`async fn` 의 본문 안**에 있는 것만 잡는다.
            for 조각 in 코드.split("async fn ").skip(1) {
                // ⚠️ 함수의 끝은 **들여쓰기 0 의 `}`** 다. 다음 `fn` 을 찾는
                //    방식으로 자르면 `pub fn`·`pub(crate) fn`·`#[…]` 이 앞에
                //    오는 다음 함수를 놓쳐, **그 함수까지 이 함수의 몸으로**
                //    본다. (이 검사가 `talk.rs` 의 sync 함수를 그렇게 잘못
                //    잡았다 — 두 번째 과잉 차단이었다.)
                let 몸 = 조각.split("\n}").next().unwrap_or(조각);
                assert!(
                    !몸.contains("block_on"),
                    "{파일} 의 `async fn` 안에서 `block_on` 을 부릅니다. \
                     런타임 안에서 런타임을 시작하면 **그 자리에서 터집니다.** \
                     `.await` 로 바꾸세요 — 시험은 런타임 밖에서 돌아 통과합니다."
                );
            }
        }
    }

    /// ⚠️ **검사를 넣으면 좋은 글도 지나가는지 같이 본다.**
    ///
    /// 2026-08-27 에 두 번 밟은 지뢰다 — 안전장치가 정상 입력을 막았다.
    /// 정직한 문장이 이 검사에 걸리면 사람이 정직하게 쓰기를 포기한다.
    #[test]
    fn 정직한_문장은_막지_않는다() {
        for 괜찮은글 in [
            "처음이면 며칠 걸릴 수 있습니다 — 남은 시간은 「이 컴퓨터」에서 보입니다.",
            "보낸 주소를 찾지 못했습니다. 손님에게 물어봐 주세요.",
            "자산은 이 길로 못 봅니다. 없는 것이 아니라 못 본 것입니다.",
            "내 화면에서만 숨깁니다. 그 사람은 계속 쓸 수 있습니다.",
            "가게 컴퓨터가 꺼져 있습니다. 기다려도 열리지 않으니 전화해 보세요.",
        ] {
            for 금지 in [
                "몇 분", "곧 됩니다", "금방 끝", "잠시만 기다", "평생", "영원히 보장",
                "절대 안 됩니다", "100% 안전", "강퇴", "쫓아내기",
            ] {
                assert!(
                    !괜찮은글.contains(금지),
                    "정직한 문장이 검사에 걸립니다: {괜찮은글:?} 에서 {금지:?}. \
                     검사가 좋은 글을 막으면 사람이 정직하게 쓰기를 포기합니다."
                );
            }
        }
    }
}
