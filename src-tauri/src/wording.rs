//! **투자처럼 들리는 말을 못 쓰게 막는다.**
//!
//! ## 🔴 왜 이 파일이 있나 — 그록 자문 (2026-08-27)
//!
//! > 대표 실명으로 **회원권을 직접 찍어 뿌리고**, 그 홀더만 말하는 공개 방을
//! > SNS 에 초대하는 구조. 방이 「이 코인 가진 사람 **혜택/수익**」으로
//! > 한 번만 오해되면, **지울 수 없는** Nostr·체인 글 + 도메인·앱·발행 지갑이
//! > 한 개인사업자에게 묶여 **특금법·유사수신 외관**이 생긴다.
//! > 대표는 클럽장이 아니라, 각 가게가 자기 회원권을 찍게 두는 **도구 제공자**여야 한다.
//!
//! 체인에 새긴 글과 릴레이로 나간 글은 **지울 수 없다.** 화면 문구는 고치면
//! 되지만 이미 나간 글은 못 거둔다. 그래서 나가기 전에 막는다.
//!
//! ## 무엇을 막나
//!
//! 「수익·배당·투자·시세·오르면·떡상」처럼 **가지고 있으면 돈이 된다**는
//! 뜻으로 읽히는 말. 자산은 **입장권이자 회원권**이지 투자 상품이 아니다.
//!
//! ## ⚠️ 사람이 쓰는 글은 막지 않는다
//!
//! 이건 **우리가 만든 화면 문구**를 검사한다. 사장이 방에 쓰는 글까지
//! 검열하면 그건 우리가 하지 않기로 한 일이고, 할 수도 없다(공개 릴레이).
//! 우리가 책임질 수 있는 것은 **우리가 적은 말**이다.

/// 투자처럼 들리는 낱말.
pub const BANNED: &[&str] = &[
    "수익", "배당", "투자", "시세", "떡상", "오르면", "차익", "이자",
    "원금", "보장", "수익률", "고수익", "재테크",
];

/// 이 문구에 걸리는 말이 있나.
pub fn risky(text: &str) -> Vec<&'static str> {
    BANNED.iter().copied().filter(|w| text.contains(w)).collect()
}

#[cfg(test)]
mod tests {
    use super::{risky, BANNED};

    /// 🔴 **우리 화면 문구에 투자처럼 들리는 말이 없어야 한다.**
    ///
    ///    체인과 릴레이로 나간 글은 못 지운다. 화면은 고칠 수 있지만
    ///    그 화면을 보고 사람이 퍼뜨린 말은 못 거둔다.
    ///
    ///    ⚠️ 검사 범위는 **자산·방·초대**를 다루는 파일로 좁힌다. 지갑
    ///       화면에서 「원금」 같은 말을 쓰는 것까지 막으면 과하다.
    #[test]
    fn 자산_방_초대_문구에_투자_어휘가_없다() {
        for (name, src) in [
            ("talk.rs", include_str!("talk.rs")),
            ("issue2.rs", include_str!("issue2.rs")),
        ] {
            // 시험 글은 뺀다 — 여기에 낱말을 적어 놨으니 자기를 센다.
            let end = src.find("#[cfg(test)]").unwrap_or(src.len());
            let hit = risky(&src[..end]);
            assert!(
                hit.is_empty(),
                "{name} 에 투자처럼 들리는 말이 있습니다: {hit:?}\n\
                 자산은 입장권·회원권입니다. 가지고 있으면 돈이 된다는 뜻으로 \
                 읽히면 유사수신 외관이 생기고, 체인에 나간 글은 못 지웁니다."
            );
        }
    }

    /// 막는 낱말이 실제로 걸리는지. 목록만 있고 안 도는 검사가 되면 안 된다.
    #[test]
    fn 실제로_걸린다() {
        assert!(!risky("이 코인 가지고 계시면 수익이 납니다").is_empty());
        assert!(!risky("원금 보장").is_empty());
        // 평범한 문구는 통과해야 한다. 과하게 막으면 아무도 안 쓴다.
        assert!(risky("이 자산을 가진 분만 이 방에 글을 씁니다").is_empty());
        assert!(risky("가게 회원권입니다. 계산대에서 받으실 수 있습니다.").is_empty());
        assert!(BANNED.len() >= 10, "막는 말이 너무 적습니다");
    }
}

#[cfg(test)]
mod 화면검사 {
    /// 🔴 금지어 검사가 **화면을 안 보고 있었다.**
    ///
    /// `talk.rs`·`issue2.rs` 만 훑느라, 1차 메뉴 「나눠주기」를 누르면 나오는
    /// 화면 제목이 **「배당」**인 것을 여섯 달 동안 아무도 못 봤다. 금지한
    /// 이유(투자로 읽히면 규제 대상이 된다)는 화면에서 더 크게 적용된다 —
    /// 사람이 실제로 읽는 것은 러스트 소스가 아니라 그 글자다.
    /// `<!-- -->` 와 `/* */` 를 통째로 지운다.
    fn 주석없이(src: &str) -> String {
        let mut out = String::with_capacity(src.len());
        let b = src.as_bytes();
        let (mut i, mut html, mut css) = (0usize, false, false);
        while i < b.len() {
            if !html && !css && b[i..].starts_with(b"<!--") {
                html = true;
                i += 4;
            } else if html && b[i..].starts_with(b"-->") {
                html = false;
                i += 3;
            } else if !html && !css && b[i..].starts_with(b"/*") {
                css = true;
                i += 2;
            } else if css && b[i..].starts_with(b"*/") {
                css = false;
                i += 2;
            } else {
                if !html && !css {
                    out.push(b[i] as char);
                }
                i += 1;
            }
        }
        out
    }

    #[test]
    fn 화면에도_금지어가_없다() {
        // ⚠️ 주석은 사람이 못 본다. **줄 단위로 거르면 안 된다** — 여러 줄
        //    주석의 가운데 줄은 `/*` 로 시작하지 않아서 그냥 통과한다.
        //    (이 검사를 처음 돌렸을 때 CSS 주석에 걸렸다.) 블록째로 지운다.
        let html = 주석없이(include_str!("../../index.html"));
        for line in html.lines() {
            let t = line.trim_start();
            for word in ["배당", "수익률", "고수익", "재테크", "떡상"] {
                assert!(
                    !t.contains(word),
                    "화면에 「{word}」 가 보입니다. 투자로 읽히면 규제 대상이 됩니다: {t}"
                );
            }
        }
    }
}
